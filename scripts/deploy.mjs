#!/usr/bin/env node
// Deploys Last Call end to end:
//   1. sam build + sam deploy (stack "lastcall", us-east-1)
//   2. reads the stack outputs
//   3. writes web/config.js with the real API base
//   4. syncs web/ to the web bucket and invalidates CloudFront
//
// Usage: node scripts/deploy.mjs [--web-only] [--stack lastcall] [--region us-east-1]
// Requires the SAM CLI and AWS CLI with credentials for the target account.

import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { refreshWindowsPath, run } from './lib/run.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { values: flags } = parseArgs({
  options: {
    'web-only': { type: 'boolean', default: false },
    stack: { type: 'string', default: 'lastcall' },
    region: { type: 'string', default: 'us-east-1' },
  },
});
const { stack, region } = flags;

function stackOutputs() {
  const raw = run('aws', [
    'cloudformation', 'describe-stacks', '--stack-name', stack, '--region', region,
    '--query', 'Stacks[0].Outputs', '--output', 'json',
  ], { capture: true, cwd: root });
  const outputs = Object.fromEntries((JSON.parse(raw) ?? []).map((o) => [o.OutputKey, o.OutputValue]));
  for (const key of ['ApiUrl', 'WebUrl', 'WebBucketName', 'DistributionId']) {
    if (!outputs[key]) throw new Error(`Stack ${stack} has no ${key} output`);
  }
  return outputs;
}

function writeWebConfig(apiBase) {
  const file = join(root, 'web', 'config.js');
  writeFileSync(file, `// Generated by scripts/deploy.mjs. Do not commit.\nwindow.LASTCALL_CONFIG = { apiBase: ${JSON.stringify(apiBase)} };\n`);
  console.log(`\nWrote ${file}`);
}

function syncWeb(bucket) {
  const target = `s3://${bucket}`;
  // Assets first with a short browser cache, then pages and config.js with no-cache so
  // a redeploy shows up immediately. Excluded files are neither uploaded nor deleted by pass one.
  run('aws', ['s3', 'sync', 'web', target, '--delete', '--region', region,
    '--exclude', '*.html', '--exclude', 'config.js', '--cache-control', 'public,max-age=300'], { cwd: root });
  run('aws', ['s3', 'sync', 'web', target, '--region', region,
    '--exclude', '*', '--include', '*.html', '--include', 'config.js', '--cache-control', 'no-cache'], { cwd: root });
}

function invalidate(distributionId) {
  run('aws', ['cloudfront', 'create-invalidation', '--distribution-id', distributionId,
    '--paths', '/*', '--query', 'Invalidation.Id', '--output', 'text'], { cwd: root });
}

function main() {
  refreshWindowsPath();
  if (!existsSync(join(root, 'web'))) throw new Error('web/ not found next to template.yaml');

  if (!flags['web-only']) {
    run('sam', ['build'], { cwd: root });
    run('sam', ['deploy',
      '--stack-name', stack,
      '--region', region,
      '--resolve-s3',
      '--capabilities', 'CAPABILITY_IAM',
      '--no-confirm-changeset',
      '--no-fail-on-empty-changeset',
    ], { cwd: root });
  }

  const outputs = stackOutputs();
  writeWebConfig(outputs.ApiUrl);
  syncWeb(outputs.WebBucketName);
  invalidate(outputs.DistributionId);

  console.log(`
Last Call is deployed.
  API:  ${outputs.ApiUrl}
  Web:  ${outputs.WebUrl}
Smoke test: node scripts/e2e.mjs ${outputs.ApiUrl}`);
}

try {
  main();
} catch (err) {
  console.error(`\nDeploy failed: ${err.message}`);
  process.exit(1);
}
